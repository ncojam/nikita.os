const IRREG = { si: "shi", ti: "chi", tu: "tsu", hu: "fu", zi: "ji", di: "ji", du: "zu", wo: "o", nna: "n" };
const DK_BASE = { g: "k", z: "s", d: "t", b: "h", p: "h" };

export function cell(script, c, vi) {
  const ch = GRID[script][c]?.[vi];
  if (!ch || ch === "・") return null;
  const raw = c === "nn" ? "nna" : c + VOWELS[vi];
  return { ch, c, vi, ro: IRREG[raw] || raw };
}

// все знаки: ch → ячейка
export const ALL = { hira: new Map(), kata: new Map() };
for (const s of ["hira", "kata"]) for (const { c } of COLS) for (let i = 0; i < 5; i++) {
  const x = cell(s, c, i); if (x) ALL[s].set(x.ch, x);
}
export const other = ch => {   // пара в другой азбуке
  for (const [s, o] of [["hira", "kata"], ["kata", "hira"]]) {
    const x = ALL[s].get(ch); if (x) return cell(o, x.c, x.vi)?.ch;
  }
  return null;
};
// звонкая форма ⇄ основа
export function voicing(script, x) {
  if (DK_BASE[x.c]) return { base: cell(script, DK_BASE[x.c], x.vi)?.ch, mark: x.c === "p" ? "゜" : "゛" };
  const v = Object.entries(DK_BASE).filter(([, b]) => b === x.c).map(([d]) => cell(script, d, x.vi)?.ch).filter(Boolean);
  return v.length ? { voiced: v } : null;
}

